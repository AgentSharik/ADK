# Функция netutils.classify_printer_port(port) возвращает пару (тип, ip):
#   "IP_10.0.2.50"          → ("network", "10.0.2.50")
#   "\\\\PRINTSRV\\KYO-2F"  → ("shared", "")
#   "USB001"                → ("usb", "")
#
# Замени `...` на правильные значения и запусти. Если ошибёшься — pytest покажет,
# что функция вернула на самом деле. Это нормальный способ узнать ответ.

def test_printer_port_network():
    kind, ip = netutils.classify_printer_port("IP_10.0.2.50")
    assert kind == "network"
    assert ip == "10.0.2.50"           # ← подсказка: IP извлекается из порта


def test_printer_port_usb():
    kind, ip = netutils.classify_printer_port("USB001")
    assert kind == "usb"
    assert ip == ""                    # ← у USB нет IP


