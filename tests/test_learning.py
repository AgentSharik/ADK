# УРОВЕНЬ 1 — готовый тест с комментарием к каждой строке. Просто прочитай.
# ============================================================================
#
# Тестируем функцию из adk/db.py (открой её, она 6 строк):
#
#     def normalize_login(login):
#         """'CORP\\Ivanov ', 'ivanov@corp.example', 'Ivanov' → 'ivanov'."""
#
# Рецепт написания теста — всегда одинаковый, 3 шага:
#   1. ПОДГОТОВКА: придумай входные данные.
#   2. ДЕЙСТВИЕ:   вызови функцию.
#   3. ПРОВЕРКА:   assert результат == то, что ты ожидал.
#
# Откуда брать «что ожидал»? Из докстринга функции, из здравого смысла,
# или из бага, который ты только что поймал руками.


def test_normalize_login_basic():
    # --- 1. ПОДГОТОВКА: входные данные — просто строка
    raw = "CORP\\Ivanov"

    # --- 2. ДЕЙСТВИЕ: вызываем ту самую функцию из программы
    result = db.normalize_login(raw)

    # --- 3. ПРОВЕРКА: assert <условие>. Истина → тест зелёный. Ложь → красный,
    #        и pytest сам покажет, что было слева и справа от ==.
    assert result == "ivanov"


# Обычно все три шага пишут в одну строку — это то же самое, просто короче:
def test_normalize_login_variants():
    assert db.normalize_login("ivanov@corp.example") == "ivanov"   # UPN → логин
    assert db.normalize_login("  Ivanov  ") == "ivanov"            # пробелы и регистр
    assert db.normalize_login("") == ""                            # пустая строка не падает
    assert db.normalize_login(None) == ""                          # None тоже не падает


# Тест на баг. Представь: админ пожаловался, что «CORP\\ivanov@corp.example» не находится.
# Шаг 1: пишешь тест, который ВОСПРОИЗВОДИТ жалобу. Запускаешь — он красный (если баг есть).
