# УРОВЕНЬ 4 — тест с базой данных. Ничего нового: те же 3 шага.
# ============================================================================
#
# Особенность: функции db.* пишут в SQLite. Файл tests/conftest.py перед КАЖДЫМ тестом
# автоматически создаёт пустую временную базу — тебе об этом думать не надо.
# Поэтому тест ниже всегда стартует с нуля, и твоя рабочая база не пострадает.

def test_note_roundtrip():
    # ПОДГОТОВКА + ДЕЙСТВИЕ: сохраняем заметку
    note_id = db.add_note("ivanov", "выдан ноутбук", admin="admin")
    # ПРОВЕРКА: она читается обратно и в ней тот же текст
    notes = db.notes_for("ivanov")
    assert len(notes) == 1
    assert notes[0]["text"] == "выдан ноутбук"
    # ДЕЙСТВИЕ 2 + ПРОВЕРКА 2: после удаления заметок нет
    db.delete_note(note_id)
    assert db.notes_for("ivanov") == []


